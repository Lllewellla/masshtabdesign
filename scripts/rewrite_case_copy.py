def first_sentence(text: str, n: int = 200) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if not text:
        return ""
    parts = re.split(r"(?<=[.!?])\s+", text)
    s = parts[0]
    if len(s) > n:
        s = s[: n - 1].rstrip() + "…"
    return s


def ensure_serial_result(mark: str, result: str) -> str:
    result = (result or "").strip()
    if mark == MARK_SERIAL:
        if not result.lower().startswith("поставлено на серийное"):
            if result:
                return f"Поставлено на серийное производство. {result}"
            return "Поставлено на серийное производство."
    if mark == MARK_SMALL:
        if result and ("мал" in result.lower() and "сер" in result.lower()):
            return result
        if not result.lower().startswith("выпуск малой"):
            if result:
                return f"Выпуск малой серией. {result}"
            return "Выпуск малой серией."
    return result or "Итог зафиксирован на странице кейса."


def parse_fm(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    fm_raw = parts[1]
    body = parts[2].lstrip("\n")
    meta: dict = {}
    # minimal parse for fields we need
    for key in ("title", "slug", "client", "product", "mark", "location", "url", "official_case_url"):
        m = re.search(rf'^{key}:\s*"?(.*?)"?\s*$', fm_raw, re.M)
        if m:
            meta[key] = m.group(1).strip().strip('"')
    m = re.search(r"^year:\s*(\d+)", fm_raw, re.M)
    if m:
        meta["year"] = int(m.group(1))
    m = re.search(r"^client_public:\s*(true|false)", fm_raw, re.M)
    if m:
        meta["client_public"] = m.group(1) == "true"
    # lists
    for key in ("category", "services", "team"):
        m = re.search(rf"^{key}:\n((?:  - .+\n?)+)", fm_raw, re.M)
        if m:
            meta[key] = re.findall(r'- "?(.*?)"?\s*$', m.group(1), re.M)
        elif re.search(rf"^{key}:\s*\[\]\s*$", fm_raw, re.M):
            meta[key] = []
    return meta, body


def yaml_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def yaml_list(items: list[str]) -> str:
    if not items:
        return "[]"
    return "\n".join(f"  - {yaml_str(x)}" for x in items)


def render(meta: dict, copy: dict) -> str:
    slug = meta["slug"]
    mark = (meta.get("mark") or "").strip()
    client = copy.get("client", meta.get("client"))
    if client in ("null", "", None):
        client = None
    product = meta.get("product") or slug
    title = meta.get("title") or f"Дизайн: {product}"
    url = meta.get("url") or f"https://m-shtab.ru/{slug}"
    services = meta.get("services") or []
    team = meta.get("team") or []
    category = meta.get("category") or []
    task = copy["task"].strip()
    work = copy["work"].strip()
    result = ensure_serial_result(mark, copy["result"].strip())
    short_task = copy.get("short_task") or first_sentence(task, 180)
    short_work = copy.get("short_work") or (", ".join(services) if services else first_sentence(work, 160))
    short_result = copy.get("short_result") or first_sentence(result, 200)
    facts = copy.get("facts") or []
    if mark == MARK_SERIAL and not any("Поставлено на серийное" in f for f in facts):
        facts = ["Поставлено на серийное производство", *facts]
    if mark and not any(mark in f for f in facts):
        facts.append(f"Маркер портфолио: {mark}")
    if services and not any(f.startswith("Работы:") for f in facts):
        facts.append("Работы: " + ", ".join(services))
    if client and not any(f.startswith("Клиент:") for f in facts):
        facts.append(f"Клиент: {client}")
    facts.append(f"Страница: {url}")

    fm = ["---", f"title: {yaml_str(title)}", f"slug: {slug}"]
    if client:
        fm.append(f"client: {yaml_str(client)}")
        fm.append("client_public: true")
    else:
        fm.append("client: null")
        fm.append("client_public: false")
    fm.append(f"product: {yaml_str(product)}")
    if category:
        fm.append("category:")
        fm.append(yaml_list(category))
    else:
        fm.append("category: []")
    fm.append(f"mark: {yaml_str(mark)}")
    fm.append(f'location: {yaml_str(meta.get("location") or "Россия")}')
    if meta.get("year"):
        fm.append(f"year: {meta['year']}")
    fm.append('author: "Бюро промышленного дизайна «Масштаб»"')
    fm.append(f"url: {url}")
    fm.append(f"official_case_url: {meta.get('official_case_url') or url}")
    if services:
        fm.append("services:")
        fm.append(yaml_list(services))
    else:
        fm.append("services: []")
    if team:
        fm.append("team:")
        fm.append(yaml_list(team))
    else:
        fm.append("team: []")
    fm.append("---")
    fm.append("")

    body = [
        f"# {product}",
        "",
    ]
    if client:
        body.append(f"**Клиент:** {client}  ")
    else:
        body.append("**Клиент:** имя в открытую не публикуем  ")
    body.append(f"**Продукт:** {product}  ")
    if mark:
        body.append(f"**Стадия / маркер:** {mark}  ")
    body.extend(
        [
            "**Бюро:** «Масштаб», Москва  ",
            f"**Страница на сайте:** {url}",
            "",
            "## Короткая карточка",
            "",
            f"**{product}**  ",
            f"**Задача:** {short_task}  ",
            f"**Работа:** {short_work}  ",
            f"**Результат:** {short_result}",
            "",
            "## Задача",
            "",
            task,
            "",
            "## Работа",
            "",
            work,
            "",
            "## Результат",
            "",
            result,
            "",
            "## Ключевые факты для цитирования",
            "",
        ]
    )
    for f in facts:
        body.append(f"- {f}")
    if team:
        body.extend(["", "## Команда", "", ", ".join(team)])
    body.extend(
        [
            "",
            "## CTA",
            "",
            "Бриф и контакты: [m-shtab.ru](https://m-shtab.ru/) · design@m-shtab.ru · +7 495 101-22-55",
            "",
        ]
    )
    return "\n".join(fm + body)


def main() -> int:
    missing = []
    rewritten = 0
    for path in sorted(CASES.glob("*.md")):
        if path.name == "README.md":
            continue
        text = path.read_text(encoding="utf-8")
        meta, _ = parse_fm(text)
        slug = meta.get("slug") or path.stem
        meta["slug"] = slug
        if slug not in COPY:
            missing.append(slug)
            continue
        path.write_text(render(meta, COPY[slug]), encoding="utf-8")
        rewritten += 1

    # refresh index marks/clients lightly from files
    if INDEX.exists():
        data = json.loads(INDEX.read_text(encoding="utf-8"))
        data["updated"] = date.today().isoformat()
        by = {c["slug"]: c for c in data.get("cases", [])}
        for path in CASES.glob("*.md"):
            if path.name == "README.md":
                continue
            meta, _ = parse_fm(path.read_text(encoding="utf-8"))
            slug = meta.get("slug") or path.stem
            if slug in by:
                if meta.get("client") and meta["client"] != "null":
                    by[slug]["client"] = meta["client"]
                    by[slug].pop("client_public", None)
                if meta.get("mark") is not None:
                    by[slug]["mark"] = meta.get("mark") or None
        data["cases"] = list(by.values())
        INDEX.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"rewritten={rewritten} missing={len(missing)}")
    if missing:
        print("missing:", ", ".join(missing))
        return 1
    return 0


